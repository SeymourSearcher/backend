"""Timings for app/services/compute.py, per function and per realistic inventory size.

Run inside the test image so the pinned numpy/scipy and the real app/static/*.npy
are in play -- timings against a developer's own wheels prove nothing:

    scripts/bench_compute.sh            # all sizes
    scripts/bench_compute.sh --profile  # cProfile the worst offender

Inventories are generated by jittering real target hexes so matches actually
fire; uniform-random hexes would make every set-finder return nothing and look
free.
"""
import os
import sys
import time

os.environ.setdefault("DATABASE_URL", "mysql+aiomysql://u:p@127.0.0.1:1/d")
os.environ.setdefault("JWT_SECRET", "bench")
os.environ.setdefault("DISCORD_CLIENT_ID", "bench")
os.environ.setdefault("DISCORD_CLIENT_SECRET", "bench")
os.environ.setdefault("DISCORD_REDIRECT_URI", "http://localhost/cb")

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np  # noqa: E402

from app.services.compute import (  # noqa: E402
    KEY_ITEM_HEXES,
    find_custom_sets,
    find_fade_dye_sets,
    find_incomplete_armor_sets,
    find_incomplete_dye_sets,
    find_matching_seymours,
    find_sets,
    find_top_hex_matches,
    find_armor_sets,
)

SIZES = [500, 2_000, 10_000]
REPEATS = 3


def make_inventory(n: int, seed: int = 0) -> list[tuple[str, int]]:
    """n seymours, jittered around real target hexes so matches actually land."""
    rng = np.random.default_rng(seed)
    targets = [h for h, _ in KEY_ITEM_HEXES]

    out = []
    for _ in range(n):
        base = int(targets[rng.integers(len(targets))], 16)
        r, g, b = (base >> 16) & 0xFF, (base >> 8) & 0xFF, base & 0xFF
        jitter = rng.integers(-6, 7, size=3)
        r, g, b = (int(np.clip(v + j, 0, 255)) for v, j in zip((r, g, b), jitter))
        out.append((f"{r:02X}{g:02X}{b:02X}", int(rng.integers(4))))
    return out


def timed(label: str, fn, *args, **kwargs) -> tuple[str, float, object]:
    best = float("inf")
    result = None
    for _ in range(REPEATS):
        start = time.perf_counter()
        result = fn(*args, **kwargs)
        best = min(best, time.perf_counter() - start)
    return label, best, result


CASES = [
    ("find_matching_seymours(best_only)", lambda inv: find_matching_seymours(
        inv, KEY_ITEM_HEXES, threshold=10.0, best_only=True)),
    ("find_matching_seymours(all)", lambda inv: find_matching_seymours(
        inv, KEY_ITEM_HEXES, threshold=5.0, best_only=False)),
    ("find_armor_sets", find_armor_sets),
    ("find_fade_dye_sets", find_fade_dye_sets),
    ("find_sets", find_sets),
    ("find_incomplete_armor_sets", find_incomplete_armor_sets),
    ("find_incomplete_dye_sets", find_incomplete_dye_sets),
    ("find_custom_sets", lambda inv: find_custom_sets(inv, max_avg_delta_e=1.0)),
]


def size_of(result) -> str:
    if isinstance(result, tuple):
        return "+".join(str(len(r)) for r in result)
    try:
        return str(len(result))
    except TypeError:
        return "-"


def run_sizes():
    print(f"{'function':<36}" + "".join(f"{f'n={n}':>14}" for n in SIZES))
    print("-" * (36 + 14 * len(SIZES)))

    inventories = {n: make_inventory(n) for n in SIZES}
    rows = {}
    for label, fn in CASES:
        cells = []
        for n in SIZES:
            _, seconds, result = timed(label, fn, inventories[n])
            cells.append(f"{seconds * 1000:>9.1f}ms")
            rows.setdefault(label, {})[n] = seconds
        print(f"{label:<36}" + "".join(f"{c:>14}" for c in cells))

    print()
    single = timed("find_top_hex_matches", find_top_hex_matches, "A3B2C1", 3, True)
    print(f"find_top_hex_matches (single hex): {single[1] * 1e6:.0f}us")

    print()
    worst = max(rows, key=lambda k: rows[k][SIZES[-1]])
    print(f"slowest at n={SIZES[-1]}: {worst} ({rows[worst][SIZES[-1]]:.2f}s)")
    return worst


def profile(label: str):
    import cProfile
    import pstats

    fn = dict(CASES)[label]
    inventory = make_inventory(SIZES[-1])
    fn(inventory)  # warm any lazy state so it does not pollute the profile

    profiler = cProfile.Profile()
    profiler.enable()
    fn(inventory)
    profiler.disable()

    print(f"\n=== cProfile: {label} at n={SIZES[-1]} ===")
    pstats.Stats(profiler).sort_stats("cumulative").print_stats(18)


if __name__ == "__main__":
    worst = run_sizes()
    if "--profile" in sys.argv:
        profile(worst)
